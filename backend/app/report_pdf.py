"""School-office report as a PDF: attendance + progress + syllabus coverage (reportlab, no browser needed)."""

from __future__ import annotations

from datetime import date
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from . import schemas as s

ACCENT = colors.HexColor("#B95C2A")
TAGS = {"on_track": "On track", "didnt_study": "Didn't study", "studied_but_confused": "Studied but confused"}


def _fmt(iso: str) -> str:
    return date.fromisoformat(iso).strftime("%d %b %Y")


def build_report_pdf(report: s.Report, class_name: str, teacher: str) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title=f"Veda report - {class_name}", author=teacher)
    st = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=st["Heading1"], textColor=ACCENT, fontSize=18, spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=st["Heading2"], fontSize=12, spaceBefore=10, spaceAfter=4)
    small = ParagraphStyle("small", parent=st["Normal"], fontSize=9, textColor=colors.HexColor("#555555"))

    def table(rows, widths, align_right_from=1):
        t = Table(rows, colWidths=widths, repeatRows=1)
        t.setStyle(TableStyle([
            ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
            ("FONT", (0, 1), (-1, -1), "Helvetica", 9),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("BACKGROUND", (0, 0), (-1, 0), ACCENT),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F5F2EE")]),
            ("ALIGN", (align_right_from, 0), (-1, -1), "RIGHT"),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#DDDDDD")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        return t

    story = [
        Paragraph("VEDA RuralClass · Class report", h1),
        Paragraph(f"{class_name} · Teacher: {teacher}", st["Normal"]),
        Paragraph(f"{_fmt(report.from_)} to {_fmt(report.to)} · {report.school_days} school days with attendance", small),
        Spacer(1, 6),
        Paragraph("Attendance", h2),
        table([["Grade", "Attendance"]] + [[f"Grade {a.grade}", f"{a.percent}%"] for a in report.attendance_by_grade], [60 * mm, 40 * mm]),
        Paragraph("Syllabus coverage (Mathematics)", h2),
        table([["Grade", "Topics done", "Coverage", "Now teaching"]] +
              [[f"Grade {x.grade}", f"{x.done} / {x.total}", f"{x.percent}%", Paragraph(x.current_topic.title if x.current_topic else "-", small)] for x in report.syllabus],
              [25 * mm, 28 * mm, 25 * mm, 100 * mm], align_right_from=1),
        Paragraph("Student progress", h2),
        table([["Student", "Grade", "Attendance", "Avg quiz", "Avg test", "Status"]] +
              [[r.student.name, str(r.student.grade), f"{r.attendance_percent}%", f"{r.average_quiz_percent}%", f"{r.average_test_percent}%", TAGS[r.tag]] for r in report.rows],
              [45 * mm, 16 * mm, 25 * mm, 22 * mm, 22 * mm, 48 * mm]),
        Spacer(1, 8),
        Paragraph("Status: On track = steady quiz scores; Didn't study = scores falling and little practice at home; "
                  "Studied but confused = scores falling despite practice (needs re-teaching). Generated by Veda.", small),
    ]
    doc.build(story)
    return buf.getvalue()
